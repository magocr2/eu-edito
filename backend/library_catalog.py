def resolve_caption_model(style_id: str) -> dict:
    """Resolve current or legacy caption style ID to authoritative model dict."""
    sid = (style_id or "classic").strip().lower()
    mapped = LEGACY_STYLE_ALIASES.get(sid, sid)
    return dict(CAPTION_MODELS.get(mapped, CAPTION_MODELS["classic"]))


def get_public_library() -> dict:
    """Return full organized library catalog for API consumers and UI."""
    return {
        "caption_categories": CAPTION_CATEGORIES,
        "captions": list(CAPTION_MODELS.values()),
        "graphic_categories": GRAPHIC_CATEGORIES,
        "graphic_fx": GRAPHIC_EFFECTS,
        "composition_categories": COMPOSITION_CATEGORIES,
        "compositions": COMPOSITION_MODELS,
        "animations": ANIMATION_PRESETS,
    }
